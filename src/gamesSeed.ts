// Utility function to parse the raw TSV string safely into GameTrophyEntry items
export function parseRawGames(): GameTrophyEntry[] {
  const lines = RAW_GAMES_TSV.split('\n');
  const parsed: GameTrophyEntry[] = [];
  
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    
    const parts = line.split('\t');
    if (parts.length < 11) continue;
    
    const jogo = parts[0].trim();
    const platina = parseInt(parts[1], 10) || 0;
    const ouro = parseInt(parts[2], 10) || 0;
    const prata = parseInt(parts[3], 10) || 0;
    const bronze = parseInt(parts[4], 10) || 0;
    
    const isPS3 = parts[5].toUpperCase() === 'TRUE';
    const isPSVita = parts[6].toUpperCase() === 'TRUE';
    const isPS4 = parts[7].toUpperCase() === 'TRUE';
    const isPS5 = parts[8].toUpperCase() === 'TRUE';
    
    const platforms: ('PS3' | 'PSVita' | 'PS4' | 'PS5')[] = [];
    if (isPS3) platforms.push('PS3');
    if (isPSVita) platforms.push('PSVita');
    if (isPS4) platforms.push('PS4');
    if (isPS5) platforms.push('PS5');
    
    const garapa = parts[9].toUpperCase() === 'TRUE';
    const hide = parts[10].toUpperCase() === 'TRUE';
    
    let dataPlatina: string | undefined = undefined;
    if (parts[11]) {
      const rawDate = parts[11].trim();
      if (rawDate) {
        // Raw date is in DD/MM/YYYY. We need YYYY-MM-DD
        const dateParts = rawDate.split('/');
        if (dateParts.length === 3) {
          const day = dateParts[0].padStart(2, '0');
          const month = dateParts[1].padStart(2, '0');
          const year = dateParts[2];
          dataPlatina = `${year}-${month}-${day}`;
        }
      }
    }
    
    parsed.push({
      id: `game-${i}-${encodeURIComponent(jogo).slice(0, 10)}`,
      jogo,
      platina,
      ouro,
      prata,
      bronze,
      platforms,
      garapa,
      hide,
      dataPlatina
    });
  }
  
  return parsed;
}
